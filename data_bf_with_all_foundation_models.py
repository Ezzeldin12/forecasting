def lagllama_fn(ctx_window, horizon):
    ds = ListDataset([{
        FieldName.TARGET: ctx_window,
        FieldName.START: pd.Period("2016-01-01", freq="D"),
    }], freq="D")
    forecasts = list(lagllama_predictor.predict(ds))
    return np.median(forecasts[0].samples, axis=0).astype(np.float32)[:horizon]

