"""### 5. TinyTimeMixer (ibm-granite/granite-timeseries-ttm-r2-512-96)

"""

from tsfm_public.models.tinytimemixer import TinyTimeMixerForPrediction

TTM_CTX = 512

ttm_model = TinyTimeMixerForPrediction.from_pretrained(
    "ibm-granite/granite-timeseries-ttm-r2-512-96"
)
ttm_model = ttm_model.to(device)
ttm_model.eval()

def ttm_fn(ctx_window, horizon):
    ctx_raw = ctx_window[-TTM_CTX:]
    if len(ctx_raw) < TTM_CTX:
        ctx_raw = np.pad(ctx_raw, (TTM_CTX - len(ctx_raw), 0), mode="edge")
    x = torch.tensor(ctx_raw, dtype=torch.float32).unsqueeze(0).unsqueeze(-1).to(device)
    with torch.no_grad():
        output = ttm_model(past_values=x)
    return output.prediction_outputs.squeeze().cpu().numpy().astype(np.float32)[:horizon]

pred_ttm = rolling_forecast(ttm_fn, ctx_vals, test_values, ctx_cap=TTM_CTX)
store_metrics(results, 'TinyTimeMixer', actual, pred_ttm)
print("TinyTimeMixer RMSE:", results['TinyTimeMixer']['RMSE'])
del ttm_model

